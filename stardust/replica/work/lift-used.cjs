// Component-scoped lift: source rules whose selectors match elements of the given prototypes.
// usage: node lift-used.cjs <out.css> <proto.html>...
const postcss = require("postcss"); const cheerio = require("cheerio"); const fs = require("fs");
const [out, ...protos] = process.argv.slice(2);
const docs = protos.map(p => cheerio.load(fs.readFileSync(p, "utf8")));
const css = fs.readFileSync("stardust/current/assets/css/site-0.css", "utf8") + "\n" + fs.readFileSync("stardust/current/assets/css/site-1.css", "utf8");
const root = postcss.parse(css);
// LIFT_KEEP=<css>: selectors already lifted for gated archetypes (incl. their JS-state snapshots) stay lifted.
const keep = new Set(); if (process.env.LIFT_KEEP) for (const f of process.env.LIFT_KEEP.split(",")) postcss.parse(fs.readFileSync(f, "utf8")).walkRules(r => { for (const q of r.selectors) keep.add((r.parent.params || "") + "|" + q); });
const cache = new Map();
function matches(sel) {
  let s = sel.replace(/::?(before|after|marker|placeholder|selection|backdrop|-webkit-[a-z-]+|-moz-[a-z-]+)(\([^)]*\))?/g, "")
    .replace(/:(hover|focus|focus-visible|focus-within|active|visited|link|checked|disabled|target|valid|invalid|empty|defined|open|placeholder-shown|autofill|indeterminate|user-invalid)/g, "")
    .replace(/:has\(([^()]|\([^()]*\))*\)/g, "").replace(/:is\(\)/g, "").trim();
  if (!s || /^(\*|html|body|:root)$/.test(s)) return true;
  if (cache.has(s)) return cache.get(s);
  let r = false; try { r = docs.some($ => $(s).length > 0); } catch { r = false; }
  cache.set(s, r); return r;
}
let kept = 0, dropped = 0;
root.walkRules(rule => {
  if (rule.parent && rule.parent.type === "atrule" && /keyframes/i.test(rule.parent.name)) return;
  const sels = rule.selectors.filter(q => keep.has((rule.parent.params || "") + "|" + q) || matches(q));
  if (!sels.length) { rule.remove(); dropped++; return; }
  rule.selectors = sels; kept++;
  rule.walkDecls(d => { if (/^-webkit-(?!text-size|mask|line-clamp|box-orient|appearance|text-fill)/.test(d.prop) || /^-moz-|^-ms-/.test(d.prop)) d.remove(); });
});
root.walkAtRules(a => { if (/font-face/i.test(a.name)) a.remove(); });
let changed = true; while (changed) { changed = false; root.walkAtRules(a => { if (!/keyframes|font-face|import|charset|property/i.test(a.name) && a.nodes && a.nodes.length === 0) { a.remove(); changed = true; } }); }
// rehost url()s
let txt = root.toString().replace(/url\((['"]?)(\/[^)'"]+)\1\)/g, (m, q, u) => {
  const base = u.split("?")[0].split("/").pop(); return `url(${q}../assets/css-img/${base}${q})`; });
const urls = [...css.matchAll(/url\((['"]?)(\/[^)'"]+)\1\)/g)].map(m => m[2]);
txt = txt.replace(/Neue Haas Grotesk Display Pro,/g, 'Neue Haas Grotesk Display Pro,nhg-display-fallback,').replace(/Neue Haas Grotesk Text Pro,/g, 'Neue Haas Grotesk Text Pro,nhg-text-fallback,'); // R-01 metric-matched fallbacks
const header = `/* Lifted from https://beta.dc.gov theme CSS (component-scoped: only rules whose selectors match the prototype markup).\n   Font faces omitted per inconsistency register R-01. Generated by stardust/replica/work/lift-used.cjs. */\n`;
fs.writeFileSync(out, header + txt.replace(/\n{3,}/g, "\n\n"));
fs.writeFileSync(out + ".urls", [...new Set(urls)].join("\n"));
console.log(`kept ${kept} rules, dropped ${dropped}; ${txt.length} chars`);
